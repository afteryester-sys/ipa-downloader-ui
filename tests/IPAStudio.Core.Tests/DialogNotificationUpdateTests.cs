namespace IPAStudio.Core.Tests;

using System;
using IPAStudio.Core.Services;

/// <summary>
/// Unit tests for Version comparison and normalization in UpdateService,
/// Dialog abstraction, and Notification formatting.
/// </summary>
public static class DialogNotificationUpdateTests
{
    public static void RunAll()
    {
        TestVersionNormalization();
        TestVersionParsing();
        TestVersionComparison();
    }

    public static void TestVersionNormalization()
    {
        var v3 = new Version(1, 8, 76);
        var norm3 = UpdateService.NormalizeVersion(v3);
        AssertEqual(norm3.Major, 1, "Major is 1");
        AssertEqual(norm3.Minor, 8, "Minor is 8");
        AssertEqual(norm3.Build, 76, "Build is 76");
        AssertEqual(norm3.Revision, 0, "Revision normalized from -1 to 0");

        var v4 = new Version(1, 8, 76, 0);
        var norm4 = UpdateService.NormalizeVersion(v4);
        AssertEqual(norm3, norm4, "Normalized 3-part and 4-part versions are equal");
    }

    public static void TestVersionParsing()
    {
        var v1 = UpdateService.ParseVersion("v1.8.77");
        AssertEqual(v1 != null, true, "v1.8.77 parsed");
        AssertEqual(v1!.Major, 1, "Major is 1");
        AssertEqual(v1.Minor, 8, "Minor is 8");
        AssertEqual(v1.Build, 77, "Build is 77");

        var v2 = UpdateService.ParseVersion("1.8.76-beta.1");
        AssertEqual(v2 != null, true, "1.8.76-beta.1 parsed");
        AssertEqual(v2!.Build, 76, "Build is 76");

        var vEmpty = UpdateService.ParseVersion("");
        AssertEqual(vEmpty == null, true, "Empty version returns null");
    }

    public static void TestVersionComparison()
    {
        var current = new Version(1, 8, 76, 0); // As generated by Assembly.GetEntryAssembly
        var older = UpdateService.ParseVersion("v1.8.75");
        var same = UpdateService.ParseVersion("v1.8.76");
        var newer = UpdateService.ParseVersion("v1.8.77");

        AssertEqual(UpdateService.NormalizeVersion(newer!) > UpdateService.NormalizeVersion(current), true, "1.8.77 is newer than 1.8.76.0");
        AssertEqual(UpdateService.NormalizeVersion(same!) > UpdateService.NormalizeVersion(current), false, "1.8.76 is not newer than 1.8.76.0");
        AssertEqual(UpdateService.NormalizeVersion(older!) > UpdateService.NormalizeVersion(current), false, "1.8.75 is not newer than 1.8.76.0");
    }

    private static void AssertEqual<T>(T actual, T expected, string testName)
    {
        if (EqualityComparer<T>.Default.Equals(actual, expected))
        {
            Console.WriteLine($"  [PASS] {testName}");
        }
        else
        {
            Console.WriteLine($"  [FAIL] {testName}: expected {expected}, got {actual}");
            throw new Exception($"Test failed: {testName}");
        }
    }
}
